const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
function readCapture(name,expectedSHA){
  const file=new URL('fixtures/'+name,import.meta.url);
  assert.equal(sha(fs.readFileSync(file)),expectedSHA);
  const {packet,capture}=readNativeFrameHistoryDigests(file);
  assert.equal(packet.blobs,undefined);
  assert.equal(capture.reference.sourceCommit,'6f8116d0964429db0e2da41d583566784114fc5f');
  assert.equal(capture.reference.sourceSha256,'6160e43c1a74f6dc70fd9852433c3373fe11b3e55d4f3a3fedc435265591b5c5');
  assert.equal(capture.allocationInputs,undefined);
  assert.equal(capture.physicalController.completionRequired,true);
  assert.equal(capture.physicalController.result.completed,true);
  assert.deepEqual(capture.physicalController.result.errors,[]);
  assert.deepEqual(capture.flipperMotion.errors,[]);
  assert.deepEqual(capture.presentation.errors,[]);
  assert.equal(capture.playerCorrections.partyChooserSHA256,sha(partyChooserScript));
  assert.ok(capture.playerInputs.some(input=>input.script===partyChooserScript));
  const imageFrames=capture.frames.filter(frame=>Object.keys(frame.images).length);
  assert.ok(imageFrames[0].snapshot.ms<capture.physicalController.result.completedAt);
  assert.ok(imageFrames.at(-1).snapshot.ms>capture.physicalController.result.completedAt);
  for(const [index,frame]of imageFrames.entries()){
    const transmission=frame.draws.some(draw=>draw.name==='fb_blur_horiz19x19');
    assert.deepEqual(Object.keys(frame.images).sort(),['ao','bloom','depth','final','hdr','previousHDR','priorAO',...(transmission?['priorTransmissionFiltered']:[])].sort());
    if(index)assert.equal(frame.images.previousHDR.sha256,imageFrames[index-1].images.hdr.sha256);
  }
  return capture;
}

