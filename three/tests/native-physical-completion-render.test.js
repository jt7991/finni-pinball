import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {readNativeFrameHistoryDigests} from '../../scripts/native-frame-history-package.mjs';
import {compareNativeHistoryState} from '../../scripts/compare-native-history-state.mjs';
import {partyChooserScript} from '../../browser/party-chooser.js';

const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
function readCapture(name,expectedSHA){
  const file=new URL('fixtures/'+name,import.meta.url);
  assert.equal(sha(fs.readFileSync(file)),expectedSHA);
  const {packet,capture}=readNativeFrameHistoryDigests(file);
  assert.equal(packet.blobs,undefined);
  assert.equal(capture.reference.sourceCommit,'6f8116d0964429db0e2da41d583566784114fc5f');
  assert.equal(capture.reference.sourceSha256,'6160e43c1a74f6dc70fd9852433c3373fe11b3e55d4f3a3fedc435265591b5c5');
  assert.equal(capture.allocationInputs,undefined);
  assert.equal(capture.physicalController.completionRequired,true);
  assert.equal(capture.physicalController.result.completed,true);
  assert.deepEqual(capture.physicalController.result.errors,[]);
  assert.deepEqual(capture.flipperMotion.errors,[]);
  assert.deepEqual(capture.presentation.errors,[]);
  assert.equal(capture.playerCorrections.partyChooserSHA256,sha(partyChooserScript));
  assert.ok(capture.playerInputs.some(input=>input.script===partyChooserScript));
  const imageFrames=capture.frames.filter(frame=>Object.keys(frame.images).length);
  assert.ok(imageFrames[0].snapshot.ms<capture.physicalController.result.completedAt);
  assert.ok(imageFrames.at(-1).snapshot.ms>capture.physicalController.result.completedAt);
  for(const [index,frame]of imageFrames.entries()){
    const transmission=frame.draws.some(draw=>draw.name==='fb_blur_horiz19x19');
    assert.deepEqual(Object.keys(frame.images).sort(),['ao','bloom','depth','final','hdr','previousHDR','priorAO',...(transmission?['priorTransmissionFiltered']:[])].sort());
    if(index)assert.equal(frame.images.previousHDR.sha256,imageFrames[index-1].images.hdr.sha256);
  }
  return capture;
}

test('physical mission counter, win and jackpot retain native rendering history and every physical boundary',async()=>{
  const capture=readCapture('vpx-main-6f8116d-mission1-complete-render-digests-native.json.gz','e0e5d555704cfffada4ad9abb5a20488fe1b8fd8df3750b5cab772c520aacbd6');
  assert.equal(capture.physicalController.kind,'physical-mission-completion');
  assert.equal(capture.physicalController.scenario.mission,1);
  assert.equal(capture.physicalController.sourceSHA256,'fd97ecfe4d08cb3734ac3126c6c33a85ea0162183c9878347c11f762a0f4e275');
  assert.equal(capture.physicalController.result.completedAt,13839);
  assert.equal(capture.physicalController.result.last.won,1);
  assert.equal(capture.physicalController.result.last.life1,0);
  assert.equal(capture.physicalController.result.last.endJackpot,0);
  assert.equal(capture.physicalController.result.last.score,3086000);
  assert.deepEqual(capture.imageWindow,{warmupFrames:300,imageFrames:96});
  assert.equal(capture.frames[300].snapshot.ms,5838);
  assert.equal(capture.frames.at(-1).snapshot.ms,20754);
  assert.equal(capture.frames.reduce((count,frame)=>count+Object.keys(frame.images).length,0),767);
  assert.deepEqual(capture.frames[350].draws.map(draw=>draw.name),['ambient_occlusion','fb_bloom','fb_blur_horiz39x39','fb_blur_vert39x39','fb_rhtonemap_AO_no_filter']);
  assert.deepEqual(new Set(capture.actions.filter(action=>action.kind==='shot').map(action=>action.shot)),new Set(['scoop','target','loop','rightRamp','rightLoop']));
  // The captured approach statements are external test inputs. Every later
  // position, counter, Variant type and random word is generated by our model.
  assert.deepEqual(await compareNativeHistoryState(capture),{
    framesChecked:396,intervalsChecked:20754,ticks:20755,
    randomizeClockSamples:2,timerClockSamples:7,
    ruleObservationsChecked:58,ruleVariantFieldsChecked:1972,scriptRandomStatesChecked:58,
  });
});

test('Friendship and Disco retain native saver expiry, physical drains, rendering history and exact boundaries',async()=>{
  const capture=readCapture('vpx-main-6f8116d-side-complete-render-digests-native.json.gz','2982164c4b411e4249564211b53e91ab3d02d87861bdecce9d2c1844b0d5f091');
  const controller=capture.physicalController.result;
  assert.equal(capture.physicalController.kind,'physical-side-modes');
  assert.equal(capture.physicalController.sourceSHA256,'420e03ca7a249ac290b11a1f1c1bb39d17c36d28e907550682829cb49669139f');
  assert.equal(controller.completedAt,45524);
  assert.equal(controller.last.score,18860530);
  assert.equal(controller.last.onPlayfield,1);
  assert.equal(controller.last.ninja,0);
  assert.equal(controller.last.discoMB,0);
  assert.deepEqual(controller.milestones.map(row=>row.name),['launched','disco-loops','friend-one','friend-two','friendship','three-friends','friendship-ready-to-drain','friendship-ended','disco-loops-expired','disco-multiball','disco-ready-to-drain','disco-ended']);
  const milestone=name=>controller.milestones.find(row=>row.name===name);
  assert.equal(milestone('disco-loops').state.spins,50);
  assert.equal(milestone('three-friends').state.onPlayfield,3);
  assert.equal(milestone('friendship-ready-to-drain').state.saver,0);
  assert.equal(milestone('friendship-ready-to-drain').state.ninja,1);
  assert.equal(milestone('disco-multiball').state.discoMB,1);
  assert.equal(milestone('disco-multiball').state.onPlayfield,2);
  assert.deepEqual(controller.drains.map(row=>row.mode),['friendship','friendship','disco']);
  assert.deepEqual(capture.imageWindow,{warmupFrames:1600,imageFrames:128});
  assert.equal(capture.frames[1600].snapshot.ms,27502);
  assert.equal(capture.frames.at(-1).snapshot.ms,47585);
  assert.equal(capture.frames.reduce((count,frame)=>count+Object.keys(frame.images).length,0),1024);
  assert.equal(Math.max(...capture.frames.map(frame=>frame.snapshot.balls.length)),6);
  assert.deepEqual(await compareNativeHistoryState(capture),{
    framesChecked:1728,intervalsChecked:47585,ticks:47586,
    randomizeClockSamples:2,timerClockSamples:0,
    ruleObservationsChecked:321,ruleVariantFieldsChecked:10272,scriptRandomStatesChecked:321,
  });
});
