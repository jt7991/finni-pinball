def label(image, text, x, y, scale=2):
    assert x + (len(text)*6-1)*scale <= 256, text
    draw = ImageDraw.Draw(image)
    for index, char in enumerate(text):
        for row, bits in enumerate(FONT[char].split('/')):
            for col, bit in enumerate(bits):
                if bit == '1':
                    px, py = x+(index*6+col)*scale, y+row*scale
                    draw.rectangle((px, py, px+scale-1, py+scale-1), fill=CREAM)



def build():
    import runpy
    return runpy.run_path(str(ROOT/'scripts/finni-dmd-assets.py'))['build'](label,FONT)


def install(table):
    import runpy
    return runpy.run_path(str(ROOT/'scripts/finni-dmd-assets.py'))['install'](table,label,FONT)


